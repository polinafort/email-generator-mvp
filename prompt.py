STYLE_RULES = """
Пиши по-русски. Стиль: дружелюбно-деловой B2B, на «вы», без сленга, без эмодзи, без канцелярита.
Короткие абзацы, много воздуха. Можно списки и пошаговые инструкции.

ВАЖНО:
- Референс ниже — только для стиля и структуры.
- НЕ копируй из референса конкретные формулировки, названия фич, бренды, имена, должности.
- Не используй фразы из референса длиннее 3–4 слов подряд.
- Все заголовки и формулировки должны быть осмысленно адаптированы под текущую фичу/инициативу.
- Если каких-то данных нет — делай нейтральные допущения, но не выдумывай факты (цифры, гарантии).
"""

STRUCTURE_TEMPLATE = """
Обязательная структура письма:

1) Заголовок (1 строка) — приглашение/анонс про «{feature_name}».
2) Вступление (1–2 коротких абзаца): что это и какую задачу решает для ЦА.
3) Подзаголовок «Как это работает» + 1 короткий абзац.
4) Подзаголовок «Преимущества {feature_name}» (или «Преимущества») + 4–7 пунктов списком.
5) Подзаголовок «Как включить/подключить/начать пользоваться» + 4–7 шагов (нумерованный список).
6) Подзаголовок «Что учитывать перед запуском» + 3–6 пунктов списком (ограничения/нюансы).
7) CTA-строка отдельной строкой (как кнопка): «Включить {feature_name}» / «Попробовать {feature_name}» (выбери уместное).
8) Строка про справку: «Подробнее — в Справке: [вставьте ссылку]».
9) Закрывающий абзац: предложить помощь, «ответьте на письмо / напишите в поддержку».

Требования к объёму:
- Письмо компактное: без длинных полотен, без повторов.
- Абзацы по 1–3 строки.
"""

REFERENCE_STYLE = """
РЕФЕРЕНС СТИЛЯ (НЕ копировать текст, только структуру/тон):
- Короткий заголовок-приглашение
- 1–2 абзаца о пользе без “воды”
- Блок «Как это работает»
- Блок «Преимущества …» списком
- Блок «Как подключить …» шагами
- Блок «Что учитывать …» с предостережениями
- CTA отдельной строкой, может повторяться 1–2 раза
- В конце — помощь/контакт через ответ на письмо
"""


def build_prompt(audience: str, goal: str, feature_name: str, must_include: str, culture: str, context: str) -> str:
    culture = (culture or "").strip()
    context = (context or "").strip()

    structure = STRUCTURE_TEMPLATE.format(feature_name=feature_name.strip())

    return f"""
Ты — опытный email-маркетолог и редактор.

{STYLE_RULES}

Дополнительные требования от компании (если пусто — игнорируй):
{culture}

Контекст/продукт (если пусто — игнорируй):
{context}

Параметры:
- ЦА: {audience}
- Цель письма: {goal}
- Фича/инициатива: {feature_name}

Обязательные пункты (должны быть в письме дословно или очень близко по смыслу):
{must_include}

{structure}

{REFERENCE_STYLE}

Верни результат строго в Markdown в таком формате:

## Тема (3 варианта)
- ...
- ...
- ...

## Прехедер
...

## Письмо (готово к отправке)
(строго по структуре, заголовки и формулировки — под «{feature_name}»)
""".strip()
