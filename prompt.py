def _blocks_md():
    return "\n".join([f"- {k}: {v}" for k, v in BLOCK_LIBRARY.items()])


def build_planner_prompt(
    campaign_type: str,
    audience: str,
    goal: str,
    topic: str,
    must_include: str,
    culture: str,
    context: str,
    desired_length: str,
) -> str:
    is_promo = campaign_type.strip() == "Акция/скидка/спецпредложение"
    promo_guard = "" if is_promo else PROMO_FORBIDDEN_TEXT

    return f"""
Ты — email-маркетолог. Сначала составь ПЛАН письма: выбери пресет и блоки.

Правила стиля:
{STYLE_RULES}

{promo_guard}

Эталон для ориентира (только стиль/структура, не копировать текст):
<<<REFERENCE_START
{IDEAL_EMAIL_REFERENCE}
REFERENCE_END>>>

Тип рассылки (от пользователя): {campaign_type}
Тема: {topic}
ЦА: {audience}
Цель: {goal}
Длина: {desired_length} (short/medium)

Обязательные пункты:
{must_include}

Тон/культура компании (если есть):
{culture}

Контекст (если есть):
{context}

Доступные пресеты:
- feature, promo, webinar, holiday, newsletter, reactivation, survey

Библиотека блоков:
{_blocks_md()}

Твоя задача:
- Выбери preset_id.
- Собери blocks (порядок важен). Можно добавлять/убирать блоки.
- benefits_title должен соответствовать теме (никаких «условий акции» если это не promo).
- cta_text и include_help_link — по ситуации.

ОБЯЗАТЕЛЬНЫЕ правила выбора блоков:
- Если тип НЕ promo: НЕ используй blocks offer и promo_terms.
- Если тип promo: обязательно добавь offer и promo_terms (если нет данных — поставь плейсхолдеры).
- Если тип webinar: обязательно event_details и registration_steps (agenda желательно).
- Если тип holiday: НЕ добавляй how_it_works и steps, если пользователь явно не просит инструкцию.

Верни СТРОГО JSON без текста вокруг:

{{
  "preset_id": "feature|promo|webinar|holiday|newsletter|reactivation|survey",
  "blocks": ["intro", "...", "cta", "help"],
  "benefits_title": "Преимущества ...",
  "cta_text": "…",
  "cta_link_placeholder": "[вставьте ссылку]",
  "include_help_link": true,
  "notes": "1 короткая причина выбора блоков"
}}
""".strip()


def build_writer_prompt(
    plan: dict,
    campaign_type: str,
    audience: str,
    goal: str,
    topic: str,
    must_include: str,
    culture: str,
    context: str,
    desired_length: str,
) -> str:
    is_promo = campaign_type.strip() == "Акция/скидка/спецпредложение"
    promo_guard = "" if is_promo else PROMO_FORBIDDEN_TEXT

    blocks = plan.get("blocks", [])
    blocks_md = "\n".join([f"- {b}: {BLOCK_LIBRARY.get(b, '')}" for b in blocks])

    return f"""
Ты — опытный email-маркетолог и редактор.

Правила стиля:
{STYLE_RULES}

{promo_guard}

Эталон для ориентира (только стиль/структура, не копировать текст):
<<<REFERENCE_START
{IDEAL_EMAIL_REFERENCE}
REFERENCE_END>>>

Вводные:
- Тип рассылки: {campaign_type}
- Тема: {topic}
- ЦА: {audience}
- Цель: {goal}
- Длина: {desired_length} (short/medium)

План (строго следуй порядку блоков):
{blocks_md}

Настройки:
- Заголовок блока выгод: {plan.get("benefits_title", "Преимущества")}
- CTA текст: {plan.get("cta_text", "Подробнее")}
- CTA ссылка: {plan.get("cta_link_placeholder", "[вставьте ссылку]")}
- include_help_link: {plan.get("include_help_link", True)}

Обязательные пункты:
{must_include}

Тон/культура (если пусто — игнорируй):
{culture}

Контекст (если пусто — игнорируй):
{context}

Верни строго в Markdown:

## Тема (3 варианта)
- ...
- ...
- ...

## Прехедер
...

## Письмо (готово к отправке)
(короткие абзацы, много воздуха, списки, 1–2 CTA строкой)

Самопроверка:
- Ничего не скопировано из референса дословно.
- Заголовки соответствуют теме письма.
- Если это не promo — нет слов «акция/скидка/промокод/условия акции».
- Обязательные пункты включены.
""".strip()


def safe_parse_json(text: str) -> dict:
    text = text.strip()
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1 and end > start:
        text = text[start : end + 1]
    return json.loads(text)
