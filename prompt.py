def build_prompt(audience, goal, must_include, culture, context):
    must_include = must_include.strip()
    culture = culture.strip()
    context = context.strip()

    return f"""
Ты — опытный email-маркетолог и копирайтер. Пиши по-русски.
Задача: сгенерировать короткое, живое письмо, как будто написал человек.
Не перегружай. Избегай канцелярита, "воды" и слишком длинных абзацев.
Если данных не хватает — НЕ задавай вопросы, а сделай разумные допущения.

Дано:
- ЦА: {audience}
- Цель письма: {goal}
- Обязательные пункты (должны быть в письме дословно или очень близко по смыслу):
{must_include}

- Культура/тон компании:
{culture}

- Контекст/продукт (если есть):
{context}

Верни результат строго в Markdown со следующей структурой:

## Тема (варианты)
- ...
- ...
- ...

## Прехедер
...

## Письмо
(3–8 коротких абзацев, можно со списком, если уместно)

## CTA
Текст кнопки: "..."
Ссылка (если неизвестна — напиши [вставьте ссылку])

## Примечания (для маркетолога)
- 2–4 пункта: что ты учёл, где сделал допущения
""".strip()
